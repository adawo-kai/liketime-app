package com.liketime.device;

public enum EventMatchStatus {
    /** Событие сопоставлено с учеником и занятием (отметка поставлена или уже была) */
    MATCHED,
    /** Лицо на устройстве не привязано ни к одному ученику */
    UNKNOWN_PERSON,
    /** Устройство распознало лицо с уверенностью ниже порога */
    LOW_CONFIDENCE,
    /** Ученик известен, но в это время у него нет занятия */
    NO_LESSON,
    /** Событие намеренно не учтено: ученик неактивен или период закрыт */
    IGNORED
}
